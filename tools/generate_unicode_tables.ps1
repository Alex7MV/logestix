param(
    [string]$UcdVersion = "16.0.0",
    [string]$OutFile = "libs/lsxcommon/src/unicode_tables.inc"
)

$ErrorActionPreference = "Stop"

function Download-File([string]$Uri, [string]$OutFile) {
    # .NET HttpClient is used instead of Invoke-WebRequest: some networks
    # stall on IWR/curl transfers from unicode.org but complete via .NET TLS.
    if ((Test-Path $OutFile) -and (Get-Item $OutFile).Length -gt 0) {
        Write-Host "cached $OutFile, skipping download"
        return
    }
    for ($attempt = 1; $attempt -le 5; $attempt++) {
        try {
            $client = New-Object System.Net.Http.HttpClient
            $client.Timeout = [TimeSpan]::FromSeconds(120)
            $stream = [System.IO.File]::Create($OutFile)
            try {
                $client.SendAsync(
                    (New-Object System.Net.Http.HttpRequestMessage(
                        [System.Net.Http.HttpMethod]::Get, $Uri))
                ).Result.Content.CopyToAsync($stream).Wait()
            } finally {
                $stream.Dispose()
            }
            $client.Dispose()
            if ((Get-Item $OutFile).Length -gt 0) { return }
            Write-Warning "attempt ${attempt}: empty download, retrying..."
            Start-Sleep -Seconds 2
        } catch {
            Write-Warning "attempt ${attempt} failed: $($_.Exception.InnerException.Message)"
            Start-Sleep -Seconds 2
        }
    }
    throw "failed to download $Uri after 5 attempts"
}

