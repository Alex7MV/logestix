#!/usr/bin/env python3
"""Generate libs/lsxcommon/src/unicode_nfc_tables.inc (Unicode NFC data).

The canonical decomposition, combining-class and composition-pair tables are
derived from Python's `unicodedata` (CPython 3.14 ships UCD 16.0.0, the same
version as unicode_tables.inc). Re-run with a newer Python to move to a newer
UCD:

    python3 tools/generate_unicode_nfc_tables.py

Composition pairs are the *immediate* binary canonical decompositions that
UAX #15 actually recomposes; Python's NFC is used as the oracle so the
composition-exclusion table is honoured without vendoring CompositionExclusions.

Hangul syllables are NOT tabulated: UAX #15 composes/decomposes them
algorithmically.
"""
import sys
import unicodedata

OUT = "libs/lsxcommon/src/unicode_nfc_tables.inc"

SBASE, LBASE, VBASE, TBASE = 0xAC00, 0x1100, 0x1161, 0x11A7
LCOUNT, VCOUNT, TCOUNT = 19, 21, 28
NCOUNT, SCOUNT = VCOUNT * TCOUNT, LCOUNT * VCOUNT * TCOUNT


def is_hangul_syllable(cp):
    return SBASE <= cp < SBASE + SCOUNT


def immediate_decomp(cp):
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith("<"):
        return None
    return [int(x, 16) for x in d.split()]


def full_decomp(cp, out):
    parts = immediate_decomp(cp)
    if parts is None:
        out.append(cp)
        return
    for p in parts:
        full_decomp(p, out)


def main():
    decomps = []          # (cp, [full canonical decomposition] not equal [cp])
    composes = []         # (first, second, composed)
    combining = []        # (cp, ccc)

    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        if is_hangul_syllable(cp):
            continue
        ccc = unicodedata.combining(chr(cp))
        if ccc:
            combining.append((cp, ccc))
        parts = immediate_decomp(cp)
        if parts is not None:
            full = []
            full_decomp(cp, full)
            if full != [cp]:
                decomps.append((cp, full))
            # UAX #15 only has composition mappings for binary decompositions;
            # keep the pair iff NFC actually composes it (exclusions removed).
            if len(parts) == 2:
                a, b = parts
                if unicodedata.normalize("NFC", chr(a) + chr(b)) == chr(cp):
                    composes.append((a, b, cp))

    composes.sort()
    data = []
    entries = []
    for cp, seq in decomps:
        entries.append((cp, len(data), len(seq)))
        data.extend(seq)

    def u32(v):
        return f"0x{v:04X}"

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/generate_unicode_nfc_tables.py from Python\n")
        f.write(f"// unicodedata {unicodedata.unidata_version} (Unicode "
                f"{unicodedata.unidata_version} UCD). DO NOT EDIT.\n")
        f.write("//\n")
        f.write("// The Unicode data used to generate this file is distributed under the\n")
        f.write("// Unicode License V3 (https://www.unicode.org/license.txt):\n")
        f.write("//   Copyright (c) 1991-2026 Unicode, Inc. All Rights Reserved.\n")
        f.write("// Full license text: see THIRD_PARTY_NOTICES (section 8).\n")
        f.write("#ifndef LOGESTIX_UNICODE_NFC_TABLES_INC\n")
        f.write("#define LOGESTIX_UNICODE_NFC_TABLES_INC\n")
        f.write("#include <cstddef>\n#include <cstdint>\n")
        f.write("namespace lsxcommon {\nnamespace unicode {\n\n")
        f.write("// Canonical decomposition (recursive, Hangul excluded).\n")
        f.write("struct NfcDecompEntry { uint32_t cp; uint32_t offset; uint8_t len; };\n")
        f.write("constexpr uint32_t kNfcDecompData[] = {\n")
        for i in range(0, len(data), 8):
            f.write("    " + ", ".join(u32(v) for v in data[i:i + 8]) + ",\n")
        f.write("};\n")
        f.write("constexpr NfcDecompEntry kNfcDecomps[] = {\n")
        for cp, off, ln in entries:
            f.write(f"    {{{u32(cp)}, {off}, {ln}}},\n")
        f.write("};\n")
        f.write("constexpr size_t kNfcDecompsCount =\n    sizeof(kNfcDecomps) / sizeof(kNfcDecomps[0]);\n\n")
        f.write("// Canonical composition pairs (immediate, composition exclusions removed).\n")
        f.write("struct NfcComposeEntry { uint32_t first; uint32_t second; uint32_t composed; };\n")
        f.write("constexpr NfcComposeEntry kNfcComposes[] = {\n")
        for a, b, c in composes:
            f.write(f"    {{{u32(a)}, {u32(b)}, {u32(c)}}},\n")
        f.write("};\n")
        f.write("constexpr size_t kNfcComposesCount =\n    sizeof(kNfcComposes) / sizeof(kNfcComposes[0]);\n\n")
        f.write("// Non-zero canonical combining classes.\n")
        f.write("struct NfcCombiningEntry { uint32_t cp; uint8_t ccc; };\n")
        f.write("constexpr NfcCombiningEntry kNfcCombining[] = {\n")
        for cp, ccc in combining:
            f.write(f"    {{{u32(cp)}, {ccc}}},\n")
        f.write("};\n")
        f.write("constexpr size_t kNfcCombiningCount =\n    sizeof(kNfcCombining) / sizeof(kNfcCombining[0]);\n\n")
        f.write("} // namespace unicode\n} // namespace lsxcommon\n")
        f.write("#endif\n")
    print("wrote", OUT, "decomps", len(entries), "seq", len(data),
          "composes", len(composes), "combining", len(combining))


if __name__ == "__main__":
    sys.exit(main())
